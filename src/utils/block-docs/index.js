// Per-block flowgraph docs (docs/blocks/<block>/): the block catalog comes from
// the bridge (`blocks` command), so parameter tables never drift; prose and
// the runnable example are hand-written next to the generated README:
//   docs/blocks/<block>/about.md      front matter (group, summary, related) + prose
//   docs/blocks/<block>/example.json  {description, prompt, blocks, links, panes,
//                                      needs?, substitute?: {note, blocks: {id: {type, params}}, add?: {blocks, links}},
//                                      requires?, media?, template?, flowgraphH?, shotWaitMs?}
//   docs/blocks/<block>/README.md     generated (bin/block-docs.js)
//   docs/blocks/<block>/screenshot.png  bin/block-shots.js
// Examples use "$MEDIA" (the media dir with generated test files) and "$PORT"
// (a free port) placeholders; `substitute` swaps blocks that need hardware for
// runnable stand-ins in tests and screenshots.

