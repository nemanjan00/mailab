/**
 * JSON-lines client for a bridge process: command(name, args) -> result;
 * every other message goes to onMessage.
 * @param {Object} child spawned bridge process
 * @param {function(Object)} [onMessage]
 */
const bridgeClient = (child, onMessage) => {
	const pending = {};
	let buffer = "";
	let nextId = 1;
	child.stdout.on("data", (d) => {
		buffer += d;
		const lines = buffer.split("\n");
		buffer = lines.pop();
		lines.forEach((line) => {
			let msg;
			try {
				msg = JSON.parse(line);
			} catch (_err) {
				return;
			}
			if (msg.type === "result" && pending[msg.id]) {
				const p = pending[msg.id];
				delete pending[msg.id];
				if (msg.error) {
					p.reject(new Error(msg.error));
				} else {
					p.resolve(msg.result);
				}
			} else if (onMessage) {
				onMessage(msg);
			}
		});
	});
	return {
		command: (name, args) => {
			const id = nextId++;
			return new Promise((resolve, reject) => {
				pending[id] = { resolve: resolve, reject: reject };
				child.stdin.write(JSON.stringify({ id: id, command: name, args: args || {} }) + "\n");
			});
		}
	};
};

/**
 * Start a flowgraph bridge, optionally with a graph.
 * @param {Object} [graph] {blocks, links}
 * @param {Object} [options] {env, onMessage}
 * @returns {{child: Object, client: Object, stderr: function(): string}}
 */
const startBridge = (graph, options) => {
	const opts = options || {};
	const args = ["flowgraph_bridge.py"].concat(graph ? ["--graph", JSON.stringify(graph)] : []);
	const child = spawn(config.get("PYTHON"), args, { cwd: PYTHON_DIR, env: Object.assign({}, process.env, opts.env || {}) });
	let stderr = "";
	child.stderr.on("data", (d) => {
		stderr += d;
	});
	return { child: child, client: bridgeClient(child, opts.onMessage), stderr: () => stderr };
};

/**
 * The block catalog straight from the bridge: name -> {kind, doc, inputs, outputs, params}.
 */
const loadCatalog = () => {
	const bridge = startBridge();
	const timer = setTimeout(() => bridge.child.kill(), CATALOG_TIMEOUT_MS);
	return bridge.client.command("blocks")
		.then((catalog) => {
			clearTimeout(timer);
			bridge.child.kill();
			return catalog;
		}, (err) => {
			clearTimeout(timer);
			bridge.child.kill();
			throw err;
		});
};

const blockDir = (name) => path.join(DOCS_DIR, name);

/**
 * about.md: YAML front matter (group, summary, related) + markdown prose.
 */
const readAbout = (name) => {
	const file = path.join(blockDir(name), "about.md");
	const text = fs.readFileSync(file, "utf8");
	const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
	if (!match) {
		throw new Error(file + ": missing front matter (---\\ngroup: ...\\n---)");
	}
	const meta = yaml.load(match[1]) || {};
	if (!GROUPS.some((g) => g.id === meta.group)) {
		throw new Error(file + ": group must be one of " + GROUPS.map((g) => g.id).join(", "));
	}
	if (!meta.summary) {
		throw new Error(file + ": missing summary (one line for the index)");
	}
	return { group: meta.group, summary: meta.summary, related: meta.related || [], body: match[2].trim() };
};

const readExample = (name) => {
	return JSON.parse(fs.readFileSync(path.join(blockDir(name), "example.json"), "utf8"));
};

/**
 * Blocks with a docs directory (an example.json).
 */
const documentedBlocks = () => {
	if (!fs.existsSync(DOCS_DIR)) {
		return [];
	}
	return fs.readdirSync(DOCS_DIR).filter((name) => fs.existsSync(path.join(blockDir(name), "example.json"))).sort();
};

// ---- example preparation -------------------------------------------------------

const mapStrings = (value, fn) => {
	if (typeof value === "string") {
		return fn(value);
	}
	if (Array.isArray(value)) {
		return value.map((v) => mapStrings(v, fn));
	}
	if (value && typeof value === "object") {
		const out = {};
		Object.keys(value).forEach((k) => {
			out[k] = mapStrings(value[k], fn);
		});
		return out;
	}
	return value;
};

/**
 * The graph an example runs as: placeholders filled in, `substitute` applied
 * (blocks needing hardware swapped for runnable stand-ins).
 * @param {Object} example example.json
 * @param {Object} opts {media: dir with the generated files, port: free TCP/UDP port, substitute: default true}
 * @returns {{blocks: Object[], links: Array[]}}
 */
const prepareGraph = (example, opts) => {
	const substitute = (opts.substitute !== false && example.substitute) || {};
	const swaps = substitute.blocks || {};
	const extra = substitute.add || { blocks: [], links: [] };
	const blocks = example.blocks.map((b) => {
		if (swaps[b.id]) {
			return { id: b.id, type: swaps[b.id].type, params: swaps[b.id].params || {} };
		}
		return b;
	});
	const graph = { blocks: blocks.concat(extra.blocks || []), links: example.links.concat(extra.links || []) };
	return mapStrings(graph, (s) => {
		if (s === "$PORT") {
			return opts.port;
		}
		return s.split("$MEDIA").join(opts.media);
	});
};

/**
 * Unmet `requires` of an example: [] when it can run here.
 */
const missingRequirements = (example) => {
	return (example.requires || []).map((name) => {
		if (!REQUIREMENTS[name]) {
			return "unknown requirement " + name;
		}
		return REQUIREMENTS[name]();
	}).filter((reason) => reason);
};

// ---- generated media -----------------------------------------------------------

const MEDIA_RATE = 48000;
const MEDIA_SECONDS = 6;

/**
 * Deterministic pseudo-random numbers (examples and screenshots are reproducible).
 */
const prng = (seed) => {
	let s = seed >>> 0;
	return () => {
		s = (s * 1664525 + 1013904223) >>> 0;
		return s / 4294967296;
	};
};

const gaussian = (rand) => {
	return Math.sqrt(-2 * Math.log(rand() + 1e-12)) * Math.cos(2 * Math.PI * rand());
};

/**
 * 16-bit mono WAV of a voice-like test signal with typical defects: a 150 Hz
 * buzz with formants and syllables, 50 Hz hum + harmonics, a 4 kHz whistle,
 * hiss and occasional clicks.
 */
const demoWav = () => {
	const rand = prng(1);
	const n = MEDIA_RATE * MEDIA_SECONDS;
	const pcm = Buffer.alloc(44 + n * 2);
	const header = [["RIFF", 0], ["WAVE", 8], ["fmt ", 12], ["data", 36]];
	header.forEach((h) => pcm.write(h[0], h[1], "ascii"));
	pcm.writeUInt32LE(36 + n * 2, 4);
	pcm.writeUInt32LE(16, 16);
	pcm.writeUInt16LE(1, 20);
	pcm.writeUInt16LE(1, 22);
	pcm.writeUInt32LE(MEDIA_RATE, 24);
	pcm.writeUInt32LE(MEDIA_RATE * 2, 28);
	pcm.writeUInt16LE(2, 32);
	pcm.writeUInt16LE(16, 34);
	pcm.writeUInt32LE(n * 2, 40);
	const formants = [[700, 1.0], [1200, 0.5], [2600, 0.25]];
	let phase = 0;
	Array.from({ length: n }).forEach((_v, i) => {
		const t = i / MEDIA_RATE;
		// syllables: ~3 per second, a gap between them
		const env = Math.max(0, Math.sin(Math.PI * ((t * 3) % 1))) * ((Math.floor(t * 3) % 4 === 3) ? 0 : 1);
		const f0 = 150 + 12 * Math.sin(2 * Math.PI * 0.7 * t);
		phase += 2 * Math.PI * f0 / MEDIA_RATE;
		const voice = Array.from({ length: 20 }).reduce((sum, _h, k) => {
			const f = f0 * (k + 1);
			const gain = formants.reduce((g, fm) => g + fm[1] / (1 + Math.pow((f - fm[0]) / 150, 2)), 0.05);
			return sum + gain * Math.sin(phase * (k + 1)) / (k + 1);
		}, 0);
		const hum = [1, 2, 3, 5].reduce((sum, k) => sum + 0.05 / k * Math.sin(2 * Math.PI * 50 * k * t), 0);
		const whistle = 0.04 * Math.sin(2 * Math.PI * 4000 * t);
		const click = (i % 9973 === 0) ? 0.8 : 0;
		const v = 0.6 * env * voice + hum + whistle + 0.02 * gaussian(rand) + click;
		pcm.writeInt16LE(Math.round(Math.max(-1, Math.min(1, v)) * 32767), 44 + i * 2);
	});
	return pcm;
};

const IQ_RATE = 1e6;
const IQ_SAMPLES = 250000;

/**
 * cf32 IQ at 1 MS/s: an FM carrier at -200 kHz (1 kHz tone, 25 kHz deviation),
 * a CW tone at +150 kHz and a weaker one at +300 kHz, over noise.
 */
const demoIq = () => {
	const rand = prng(2);
	const out = new Float32Array(IQ_SAMPLES * 2);
	let fmPhase = 0;
	Array.from({ length: IQ_SAMPLES }).forEach((_v, i) => {
		const t = i / IQ_RATE;
		fmPhase += 2 * Math.PI * (-200e3 + 25e3 * Math.sin(2 * Math.PI * 1e3 * t)) / IQ_RATE;
		const re = 0.5 * Math.cos(fmPhase) + 0.3 * Math.cos(2 * Math.PI * 150e3 * t) + 0.05 * Math.cos(2 * Math.PI * 300e3 * t) + 0.01 * gaussian(rand);
		const im = 0.5 * Math.sin(fmPhase) + 0.3 * Math.sin(2 * Math.PI * 150e3 * t) + 0.05 * Math.sin(2 * Math.PI * 300e3 * t) + 0.01 * gaussian(rand);
		out[2 * i] = re;
		out[2 * i + 1] = im;
	});
	return Buffer.from(out.buffer);
};

const MEDIA = {
	"demo.wav": demoWav,
	"demo.cf32": demoIq
};

/**
 * Write the media files examples use ($MEDIA/demo.wav, $MEDIA/demo.cf32) into dir.
 */
const makeMedia = (dir) => {
	fs.mkdirSync(dir, { recursive: true });
	Object.keys(MEDIA).forEach((name) => {
		const file = path.join(dir, name);
		if (!fs.existsSync(file)) {
			fs.writeFileSync(file, MEDIA[name]());
		}
	});
	return dir;
};

// ---- markdown ------------------------------------------------------------------

// catalog text -> markdown: <device>_<id> would vanish as HTML outside code spans
const escapeText = (text) => {
	return String(text || "").split("`").map((part, i) => {
		if (i % 2) {
			return part;
		}
		return part.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
	}).join("`");
};

const cell = (text) => escapeText(text).replace(/\|/g, "\\|").replace(/\n/g, " ");

const codeCell = (value) => {
	const text = JSON.stringify(value === undefined ? null : value);
	return "`" + text.replace(/\|/g, "\\|") + "`";
};

// JSON on one line, spaced like python's json.dumps (examples are written that way)
const inlineJson = (value) => {
	return JSON.stringify(value, null, 1).replace(/\n */g, " ").replace(/([[{]) /g, "$1").replace(/ ([\]}])/g, "$1");
};

const paramsTable = (params) => {
	const names = Object.keys(params || {});
	if (!names.length) {
		return "No parameters.";
	}
	const rows = names.map((name) => "| `" + name + "` | " + codeCell(params[name].default) + " | " + cell(params[name].doc) + " |");
	return ["| name | default | description |", "|---|---|---|"].concat(rows).join("\n");
};

/**
 * {blocks, links} as JSON with one block per line.
 */
const graphJson = (graph) => {
	const blocks = graph.blocks.map((b) => "    " + inlineJson(b)).join(",\n");
	return "{\n  \"blocks\": [\n" + blocks + "\n  ],\n  \"links\": " + inlineJson(graph.links) + "\n}";
};

const FLOWGRAPH_PANE = { type: "flowgraph", title: "Flowgraph", config: { device: DEVICE } };

const mcpCalls = (example) => {
	const lines = ["device_add {\"id\": \"" + DEVICE + "\", \"driver\": \"flowgraph\"}"];
	lines.push("device_command {\"id\": \"" + DEVICE + "\", \"command\": \"set_graph\", \"args\": {\"graph\": <the graph above>}}");
	if (example.template) {
		lines.push("# a ready-made template that uses this block (replaces the graph):");
		lines.push("device_command " + inlineJson({ id: DEVICE, command: "load_template", args: Object.assign({ name: example.template.name }, example.template.args || {}) }));
	}
	[FLOWGRAPH_PANE].concat(example.panes || []).forEach((pane) => {
		lines.push("pane_add " + inlineJson({ type: pane.type, title: pane.title, config: pane.config }));
	});
	return lines.join("\n");
};

const blockLink = (name, abouts, fromIndex) => {
	const href = fromIndex ? name + "/README.md" : "../" + name + "/README.md";
	return "[`" + name + "`](" + href + "): " + escapeText(abouts[name].summary);
};

/**
 * One block's README.md.
 * @param {string} name block type
 * @param {Object} catalog full catalog
 * @param {Object} abouts name -> readAbout(name), for every block
 * @param {Object} example readExample(name)
 * @param {boolean} hasShot screenshot.png exists
 */
const renderBlock = (name, catalog, abouts, example, hasShot) => {
	const block = catalog[name];
	const about = abouts[name];
	const group = GROUPS.find((g) => g.id === about.group);
	const out = [GENERATED_NOTE, "", "# `" + name + "`", "",
		"**" + block.kind + "** · " + group.title + " · [all blocks](../README.md)", "",
		"> " + escapeText(block.doc), "", about.body, "",
		"## Parameters", "", paramsTable(block.params), "",
		"## Inputs and outputs", "",
		"- **Input:** " + (block.kind === "source" ? "none (source)" : escapeText(block.inputs || "any")),
		"- **Output:** " + escapeText(block.outputs || (block.kind === "sink" ? "none" : "same as the input")), "",
		"## Example", "", escapeText(example.description), ""];
	if (example.needs) {
		out.push("**Needs:** " + escapeText(example.needs), "");
	}
	if (hasShot) {
		out.push("![" + name + " example](screenshot.png)", "");
	}
	if (example.substitute) {
		out.push("> **Screenshot uses a substitute:** " + escapeText(example.substitute.note), "");
	}
	if (example.media && example.media.length) {
		out.push("`$MEDIA` is your media directory (`DATA_DIR/media` or one of `MAILAB_MEDIA_DIRS`); the screenshot and tests use generated files ("
			+ example.media.map((m) => "`" + m + "`").join(", ") + ": see `makeMedia` in `src/utils/block-docs`).", "");
	}
	out.push("Ask the AI:", "", "> " + escapeText(example.prompt), "",
		"Graph ([example.json](example.json)):", "", "```json", graphJson(example), "```", "",
		"MCP calls:", "", "```", mcpCalls(example), "```", "");
	const related = about.related.filter((r) => abouts[r]);
	if (related.length) {
		out.push("## Related", "");
		related.forEach((r) => out.push("- " + blockLink(r, abouts, false)));
		out.push("");
	}
	return out.join("\n");
};

/**
 * docs/blocks/README.md: blocks grouped, linking to each block's directory.
 */
const renderIndex = (catalog, abouts) => {
	const names = Object.keys(catalog);
	const out = [GENERATED_NOTE, "", "# Flowgraph blocks", "",
		"Every block of the `flowgraph` device (python/flowgraph_bridge.py, python/audio_blocks.py): what it does, its parameters "
		+ "(generated from the live block catalog), inputs and outputs, a runnable example with a screenshot, and the prompt / MCP "
		+ "calls that build it. A graph is `{blocks: [{id, type, params}], links: [[from, to]]}`; each block has at most one input "
		+ "and an output can feed several blocks. Results land in the lab as traces, channels, values, blobs and audio streams "
		+ "named `" + DEVICE + "_<block id>` (for a device called `" + DEVICE + "`).", "",
		"Regenerate after changing a block or its docs: `yarn block-docs` (README files) and `yarn block-shots [block...]` (screenshots).", ""];
	GROUPS.forEach((group) => {
		const members = names.filter((n) => abouts[n] && abouts[n].group === group.id);
		if (!members.length) {
			return;
		}
		out.push("## " + group.title, "", group.blurb, "");
		members.forEach((n) => out.push("- " + blockLink(n, abouts, true)));
		out.push("");
	});
	return out.join("\n");
};

/**
 * Every generated file: path (relative to the repo) -> content.
 * @param {Object} catalog loadCatalog() result
 */
const generate = (catalog) => {
	const files = {};
	const abouts = {};
	Object.keys(catalog).forEach((name) => {
		abouts[name] = readAbout(name);
	});
	Object.keys(catalog).forEach((name) => {
		const hasShot = fs.existsSync(path.join(blockDir(name), "screenshot.png"));
		files[path.join("docs", "blocks", name, "README.md")] = renderBlock(name, catalog, abouts, readExample(name), hasShot);
	});
	files[path.join("docs", "blocks", "README.md")] = renderIndex(catalog, abouts);
	return files;
};

/**
 * Generated files whose content on disk differs (or is missing): [paths].
 */
const stale = (files) => {
	return Object.keys(files).filter((rel) => {
		const file = path.join(ROOT, rel);
		return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== files[rel];
	});
};

